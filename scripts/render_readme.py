"""Render the README Key Results block from results/*.csv.

    python scripts/render_readme.py          rewrite the block
    python scripts/render_readme.py --check  exit 1 if the README is stale
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START = "<!-- results:start (generated by scripts/render_readme.py, do not edit by hand) -->"
END = "<!-- results:end -->"


def block() -> str:
    t = pd.read_csv(ROOT / "results" / "model_comparison.csv")
    info = pd.read_csv(ROOT / "results" / "run_info.csv", index_col=0)["value"]
    g = t[t.model.str.startswith("GARCH")].iloc[0]
    lines = [
        START,
        f"Out-of-sample test window {info['test_start']} to {info['test_end']} "
        f"({info['n_test']} days; {info['n_train']} training days). Target: next-day 5-day realised volatility of SPY. "
        f"QLIKE is the normalised loss (lower is better, 0 is a perfect forecast). "
        f"DM is the Diebold-Mariano statistic on QLIKE against GARCH with Newey-West bandwidth 4; positive means the model beats GARCH.",
        "",
        "| Model | RMSE | QLIKE | MAPE | DM vs GARCH | p-value |",
        "|---|---|---|---|---|---|",
    ]
    best_q = t.qlike.idxmin()
    for i, r in t.iterrows():
        name = f"**{r.model}**" if i == best_q else r.model
        dm = "" if pd.isna(r.dm_vs_garch) else f"{r.dm_vs_garch:+.2f}"
        p = "" if pd.isna(r.dm_p) else f"{r.dm_p:.4f}"
        lines.append(f"| {name} | {r.rmse:.6f} | {r.qlike:.4f} | {r.mape:.1%} | {dm} | {p} |")
    ml = t[t.model.isin(["XGBoost", "LightGBM GBDT", "Entropy (monotone)", "Q50 (median)"])]
    ens = t[t.model.isin(["Stacking (Ridge meta)", "Sovereign Prime"])]
    gain = 1 - ml.rmse / g.rmse
    xgb = t.set_index("model").loc["XGBoost"]
    ent = t.set_index("model").loc["Entropy (monotone)"]
    lines += [
        "",
        f"- The four single ML models cut RMSE by {gain.min():.0%} to {gain.max():.0%} relative to GARCH and beat it on QLIKE; "
        f"the largest DM p-value among them is {ml.dm_p.max():.3f}.",
        f"- The two ensembles are worse than GARCH (DM {ens.dm_vs_garch.max():+.2f} or lower).",
        f"- The monotone-constrained Entropy model has {ent.qlike / xgb.qlike - 1:+.1%} QLIKE relative to unconstrained XGBoost.",
        f"- Fractional differencing order selected on the training fold: d = {info['frac_diff_d']}; GMM regimes: {info['n_regimes']}.",
        END,
    ]
    return "\n".join(lines)


def main() -> int:
    text = README.read_text()
    pat = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        print("results markers not found in README.md", file=sys.stderr)
        return 1
    new = pat.sub(lambda _: block(), text)
    if "--check" in sys.argv:
        if new != text:
            print("README Key Results block is stale: rerun the notebook and render", file=sys.stderr)
            return 1
        print("README Key Results block matches results/")
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
